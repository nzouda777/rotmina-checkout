import type { Language } from './translations'

type Entry = { en: string; he: string }

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function getAdminTranslation(key: string, lang: Language): string {
  const parts = key.split('.')
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let current: any = adminTranslations
  for (const part of parts) {
    if (current?.[part] === undefined) return key
    current = current[part]
  }
  if (current && typeof current === 'object' && lang in current) {
    return (current as Entry)[lang]
  }
  return key
}

export function createAdminT(lang: Language) {
  return (key: string, params?: Record<string, string | number>): string => {
    let str = getAdminTranslation(key, lang)
    if (params) {
      str = Object.entries(params).reduce(
        (s, [k, v]) => s.replace(`{${k}}`, String(v)),
        str
      )
    }
    return str
  }
}

